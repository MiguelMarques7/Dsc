function getCurrentLanguage() {
  const saved = localStorage.getItem('dsc_lang');
  return saved === 'en' ? 'en' : 'pt';
}

function setLanguage(lang) {
  localStorage.setItem('dsc_lang', lang);
  document.documentElement.lang = lang;
  
  // Update Header Buttons
  const btnPt = document.getElementById('btn-pt');
  const btnEn = document.getElementById('btn-en');
  if (btnPt && btnEn) {
    if (lang === 'pt') {
      btnPt.className = "px-2.5 py-1 bg-brand-dark text-white font-semibold transition-all";
      btnEn.className = "px-2.5 py-1 text-brand-muted hover:text-brand-dark transition-all";
    } else {
      btnEn.className = "px-2.5 py-1 bg-brand-dark text-white font-semibold transition-all";
      btnPt.className = "px-2.5 py-1 text-brand-muted hover:text-brand-dark transition-all";
    }
  }

  // Update DOM translations
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dictionary[lang] && dictionary[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dictionary[lang][key];
      } else {
        el.innerText = dictionary[lang][key];
      }
    }
  });

  // Re-trigger dynamic texts if needed (for Contacts pre-fill or Catalog count)
  window.dispatchEvent(new Event('languageChanged'));
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(getCurrentLanguage());
});
