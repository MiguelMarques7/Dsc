function getNestedValue(obj, path) {
  return path.split('.').reduce((acc, part) => acc && acc[part], obj);
}

function getCurrentLanguage() {
  const saved = localStorage.getItem('dsc_lang');
  return saved === 'en' ? 'en' : 'pt';
}

function setLanguage(lang) {
  localStorage.setItem('dsc_lang', lang);
  document.documentElement.lang = lang;
  
  // Update Header Buttons
  const btnPt = document.getElementById('btn-pt');
  const btnEn = document.getElementById('btn-en');
  if (btnPt && btnEn) {
    if (lang === 'pt') {
      btnPt.className = "px-2.5 py-1 bg-dsc-navy text-white font-semibold transition-all duration-200 rounded-sm";
      btnEn.className = "px-2.5 py-1 text-dsc-muted hover:text-dsc-navy transition-all duration-200 rounded-sm";
    } else {
      btnEn.className = "px-2.5 py-1 bg-dsc-navy text-white font-semibold transition-all duration-200 rounded-sm";
      btnPt.className = "px-2.5 py-1 text-dsc-muted hover:text-dsc-navy transition-all duration-200 rounded-sm";
    }
  }

  // Update DOM translations
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = getNestedValue(dictionary[lang], key);
    
    if (text) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else {
        el.innerText = text;
      }
    }
  });

  // Re-trigger dynamic texts if needed (for Contacts pre-fill or Catalog count)
  window.dispatchEvent(new Event('languageChanged'));
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(getCurrentLanguage());
});
