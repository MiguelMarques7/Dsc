/**
 * Returns currently selected language ('pt' or 'en')
 */
function getCurrentLanguage() {
  const saved = (typeof localStorage !== 'undefined') ? localStorage.getItem('dsc_lang') : null;
  return (saved === 'en') ? 'en' : 'pt';
}
window.getCurrentLanguage = getCurrentLanguage;

/**
 * Master Language Application Function (PT <-> EN)
 * @param {string} lang - 'pt' | 'en'
 */
function applyLanguage(lang) {
  const targetLang = (lang === 'en') ? 'en' : 'pt';
  
  // 1. Atualizar tag html e persistir escolha
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = targetLang;
    if (typeof document.documentElement.setAttribute === 'function') {
      document.documentElement.setAttribute('data-current-lang', targetLang);
    }
  }
  if (typeof localStorage !== 'undefined') {
    try {
      localStorage.setItem('dsc_lang', targetLang);
    } catch (e) {}
  }

  const dict = dictionary[targetLang] || dictionary.pt;

  // 2. Textos em nós normais e opções de select ([data-i18n])
  if (typeof document !== 'undefined' && typeof document.querySelectorAll === 'function') {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict && dict[key] !== undefined) {
        el.textContent = dict[key];
      } else if (dictionary.pt && dictionary.pt[key] !== undefined) {
        el.textContent = dictionary.pt[key];
        console.warn(`[i18n] Chave em falta para '${targetLang}': "${key}" (a usar fallback PT)`);
      } else {
        console.warn(`[i18n] Chave em falta para '${targetLang}': "${key}"`);
      }
    });

    // 3. Placeholders de inputs e caixas de texto ([data-i18n-placeholder])
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict && dict[key] !== undefined) {
        el.setAttribute('placeholder', dict[key]);
      } else if (dictionary.pt && dictionary.pt[key] !== undefined) {
        el.setAttribute('placeholder', dictionary.pt[key]);
        console.warn(`[i18n] Placeholder em falta para '${targetLang}': "${key}" (a usar fallback PT)`);
      } else {
        console.warn(`[i18n] Placeholder em falta para '${targetLang}': "${key}"`);
      }
    });

    // 4. Atributos de acessibilidade ([data-i18n-aria])
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      if (dict && dict[key] !== undefined) {
        if (el.hasAttribute('aria-label')) el.setAttribute('aria-label', dict[key]);
        if (el.hasAttribute('title')) el.setAttribute('title', dict[key]);
      }
    });

    // 5. Opções de seleção (<select option[data-i18n]>)
    document.querySelectorAll('select option[data-i18n]').forEach(opt => {
      const key = opt.getAttribute('data-i18n');
      if (dict && dict[key] !== undefined) {
        opt.textContent = dict[key];
      }
    });

    // 6. Atualização visual mecânica dos botões de alternância
    const btnPt = document.getElementById('btn-pt');
    const btnEn = document.getElementById('btn-en');
    if (btnPt && btnEn) {
      if (targetLang === 'pt') {
        btnPt.className = "px-2.5 py-1 bg-dsc-navy text-white font-medium transition-all";
        btnEn.className = "px-2.5 py-1 text-dsc-muted hover:text-dsc-navy transition-all";
      } else {
        btnEn.className = "px-2.5 py-1 bg-dsc-navy text-white font-medium transition-all";
        btnPt.className = "px-2.5 py-1 text-dsc-muted hover:text-dsc-navy transition-all";
      }
    }

    // Sincronizar botões adicionais no menu mobile
    document.querySelectorAll('.btn-lang-pt').forEach(btn => {
      if (btn !== btnPt) {
        btn.className = (targetLang === 'pt')
          ? "btn-lang-pt px-2 py-1 bg-dsc-navy text-white active:scale-95"
          : "btn-lang-pt px-2 py-1 text-dsc-muted active:scale-95";
      }
    });

    document.querySelectorAll('.btn-lang-en').forEach(btn => {
      if (btn !== btnEn) {
        btn.className = (targetLang === 'en')
          ? "btn-lang-en px-2 py-1 bg-dsc-navy text-white active:scale-95"
          : "btn-lang-en px-2 py-1 text-dsc-muted active:scale-95";
      }
    });
  }

  // 7. Notificar todos os módulos e componentes dinâmicos
  if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: targetLang } }));
  }
}

// Aliases
window.applyLanguage = applyLanguage;
window.setLanguage = applyLanguage;

// Auto-inicializar ao carregar o DOM
if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    const initialLang = getCurrentLanguage();
    applyLanguage(initialLang);
  });
}
