// Generate reverse lookup dictionary for restoring PT perfectly
const REVERSE_PHRASES = {};
for (const [pt, en] of Object.entries(GLOBAL_PHRASES)) {
  if (pt && en && pt !== en) {
    REVERSE_PHRASES[en] = pt;
  }
}

function getNestedValue(obj, path) {
  if (!obj || !path) return undefined;
  return path.split('.').reduce((acc, part) => acc && acc[part], obj);
}

function getCurrentLanguage() {
  const saved = localStorage.getItem('dsc_lang');
  return saved === 'en' ? 'en' : 'pt';
}

function normalizeStr(str) {
  if (!str) return '';
  return str.replace(/\s+/g, ' ').trim();
}

/**
 * Traverses all DOM text nodes recursively excluding code/script tags.
 */
function walkTextNodes(node, callback) {
  if (!node) return;
  const nodeType = node.nodeType;
  if (nodeType === Node.ELEMENT_NODE) {
    const tagName = node.tagName.toUpperCase();
    if (['SCRIPT', 'STYLE', 'TEXTAREA', 'NOSCRIPT', 'CODE', 'PRE'].includes(tagName)) {
      return;
    }
    for (let child = node.firstChild; child; child = child.nextSibling) {
      walkTextNodes(child, callback);
    }
  } else if (nodeType === Node.TEXT_NODE) {
    callback(node);
  }
}

/**
 * Translates a single text node according to target language
 */
function translateTextNode(node, lang) {
  const raw = node.nodeValue;
  if (!raw) return;
  const trimmed = raw.trim();
  if (!trimmed) return;
  const norm = normalizeStr(trimmed);

  if (lang === 'en') {
    if (node._origText === undefined) {
      node._origText = raw;
    }
    const match = GLOBAL_PHRASES[trimmed] || GLOBAL_PHRASES[norm];
    if (match) {
      const matchLead = raw.match(/^\s*/);
      const matchTrail = raw.match(/\s*$/);
      const lead = matchLead ? matchLead[0] : '';
      const trail = matchTrail ? matchTrail[0] : '';
      node.nodeValue = lead + match + trail;
    }
  } else {
    // Returning to PT
    if (node._origText !== undefined) {
      node.nodeValue = node._origText;
    } else {
      const match = REVERSE_PHRASES[trimmed] || REVERSE_PHRASES[norm];
      if (match) {
        const matchLead = raw.match(/^\s*/);
        const matchTrail = raw.match(/\s*$/);
        const lead = matchLead ? matchLead[0] : '';
        const trail = matchTrail ? matchTrail[0] : '';
        node.nodeValue = lead + match + trail;
      }
    }
  }
}

/**
 * Translates an arbitrary DOM container element
 */
function translateElement(rootEl, lang) {
  const targetLang = lang || getCurrentLanguage();
  walkTextNodes(rootEl, (node) => {
    translateTextNode(node, targetLang);
  });
}

/**
 * Master setLanguage function
 * Updates DOM attributes, buttons, titles, placeholders, select options, and all text nodes.
 */
function setLanguage(lang) {
  const normalizedLang = (lang === 'en') ? 'en' : 'pt';
  localStorage.setItem('dsc_lang', normalizedLang);
  document.documentElement.lang = normalizedLang;

  // 1. Update Header and Mobile Language Switcher Buttons
  const ptButtons = document.querySelectorAll('.btn-lang-pt');
  const enButtons = document.querySelectorAll('.btn-lang-en');

  ptButtons.forEach(btn => {
    if (normalizedLang === 'pt') {
      btn.className = "btn-lang-pt px-2.5 py-1 bg-dsc-navy text-white font-normal transition-all rounded-none active:scale-95";
    } else {
      btn.className = "btn-lang-pt px-2.5 py-1 text-dsc-muted hover:text-dsc-navy transition-all rounded-none active:scale-95";
    }
  });

  enButtons.forEach(btn => {
    if (normalizedLang === 'en') {
      btn.className = "btn-lang-en px-2.5 py-1 bg-dsc-navy text-white font-normal transition-all rounded-none active:scale-95";
    } else {
      btn.className = "btn-lang-en px-2.5 py-1 text-dsc-muted hover:text-dsc-navy transition-all rounded-none active:scale-95";
    }
  });

  // 2. Update Page Title
  const currentPath = window.location.pathname.split('/').pop() || 'index.html';
  if (PAGE_TITLES[currentPath] && PAGE_TITLES[currentPath][normalizedLang]) {
    document.title = PAGE_TITLES[currentPath][normalizedLang];
  }

  // 3. Update Elements with [data-i18n]
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = getNestedValue(dictionary[normalizedLang], key);
    
    if (text !== undefined && text !== null) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el._origPlaceholder === undefined) el._origPlaceholder = el.placeholder;
        el.placeholder = (normalizedLang === 'pt' && el._origPlaceholder) ? el._origPlaceholder : text;
      } else {
        if (el._origHTML === undefined) {
          el._origHTML = el.innerHTML;
        }
        if (normalizedLang === 'pt') {
          if (el._origHTML !== undefined) {
            el.innerHTML = el._origHTML;
          } else {
            el.innerHTML = text;
          }
        } else {
          el.innerHTML = text;
        }
      }
    }
  });

  // 4. Translate all text nodes throughout the page body
  walkTextNodes(document.body, (node) => {
    translateTextNode(node, normalizedLang);
  });

  // 5. Translate input & textarea placeholders
  document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
    if (normalizedLang === 'en') {
      if (el._origPlaceholder === undefined) {
        el._origPlaceholder = el.placeholder;
      }
      const trimmed = el.placeholder.trim();
      const norm = normalizeStr(trimmed);
      if (GLOBAL_PHRASES[trimmed]) {
        el.placeholder = GLOBAL_PHRASES[trimmed];
      } else if (GLOBAL_PHRASES[norm]) {
        el.placeholder = GLOBAL_PHRASES[norm];
      }
    } else {
      if (el._origPlaceholder !== undefined) {
        el.placeholder = el._origPlaceholder;
      } else {
        const trimmed = el.placeholder.trim();
        const norm = normalizeStr(trimmed);
        if (REVERSE_PHRASES[trimmed]) {
          el.placeholder = REVERSE_PHRASES[trimmed];
        } else if (REVERSE_PHRASES[norm]) {
          el.placeholder = REVERSE_PHRASES[norm];
        }
      }
    }
  });

  // 6. Translate select option texts
  document.querySelectorAll('select option').forEach(opt => {
    if (normalizedLang === 'en') {
      if (opt._origText === undefined) {
        opt._origText = opt.text;
      }
      const trimmed = opt.text.trim();
      const norm = normalizeStr(trimmed);
      if (GLOBAL_PHRASES[trimmed]) {
        opt.text = GLOBAL_PHRASES[trimmed];
      } else if (GLOBAL_PHRASES[norm]) {
        opt.text = GLOBAL_PHRASES[norm];
      }
    } else {
      if (opt._origText !== undefined) {
        opt.text = opt._origText;
      } else {
        const trimmed = opt.text.trim();
        const norm = normalizeStr(trimmed);
        if (REVERSE_PHRASES[trimmed]) {
          opt.text = REVERSE_PHRASES[trimmed];
        } else if (REVERSE_PHRASES[norm]) {
          opt.text = REVERSE_PHRASES[norm];
        }
      }
    }
  });

  // 7. Dispatch event for dynamic subcomponents (blog cards, spec modals, form scripts)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: normalizedLang } }));
}

